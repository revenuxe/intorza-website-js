The single fastest way to lose money in interior design is to under-price the quotation. The second fastest is to over-price and lose the project. Here is a framework that gets you closer to the right number every time.

## Start with one decision: pricing model

There are five pricing models in interior work. Pick the one that fits the project — sometimes one project mixes two or three.

### 1. Per square foot (most common for residential turnkey)

Quote a single rupee-per-sqft rate for the whole flat (e.g., ₹1,800/sqft for a 3BHK turnkey at a mid-finish spec). Simple for the client, dangerous for you if scope changes.

**Use when:** scope is well-defined, finish level is locked, you have done similar projects to benchmark.

### 2. Per running foot (wardrobes, TV units, kitchens)

Quote ₹/rft for carcass-and-finish. Then add hardware, handles, accessories as separate items.

**Use when:** modular work, where dimensions vary but spec is consistent.

### 3. Per piece (furniture and loose items)

Quote per chair, per sofa, per dining table. Always quote with full specification (size, material, finish).

### 4. Lump sum (design fee, supervision)

A single number for a scope of *service* — design fee, project management, site supervision. Usually 5–15% of project cost.

### 5. Hourly (consultation, change orders)

For ad-hoc work outside the main scope. Be explicit about the hourly rate in your terms.

## Build your rate from cost upward

A pricing rate is not a guess. It is:

```
Material cost
+ Labour cost
+ Wastage (typically 5–10%)
+ Site logistics
+ Overhead allocation (rent, salaries, software)
+ Margin (your profit)
= Quoted rate
```

If you do not know your overhead allocation per project, you do not know your margin. Most studios over-discount because they underestimate this number.

## How to compute overhead allocation

Take your monthly fixed cost (rent + salaries + software + utilities + marketing). Divide by the number of projects you typically deliver in a month. That is your overhead per project. Add this to every quotation before you compute margin.

Example: ₹4,00,000/month fixed cost, 4 projects delivered. Overhead per project = ₹1,00,000. A project under ₹1,00,000 in total cost is a guaranteed loss before you even start.

## Set a target margin and protect it

Healthy interior margins in India are:

- **Design fee only:** 50–70% gross margin.
- **Supply-and-fix turnkey:** 20–35% gross margin.
- **Supply-only modular:** 25–40%.
- **Civil and labour-heavy:** 15–25%.

Set your minimum margin per category. Good [quotation software](/blog/quotation-software-features-interior-designers) will warn you when a discount breaches it.

## Pricing psychology that wins more projects

- **Anchor with the full spec.** "Greenply BWP + Hettich + Greenlam" justifies a higher rate than the same dimensions with no brand.
- **Tier the quotation.** Good / Better / Best version of the same project. Clients pick "Better" 70% of the time.
- **Bundle small items.** Do not quote ₹150 for door stoppers. Bundle into "Site finishing kit — ₹4,500".
- **Show the discount.** A 5% line-item shows generosity; the same lower rate without a line is invisible.

## Common pricing mistakes

- **No overhead in the rate.** Margin disappears at the GST line.
- **Same rate for every room.** Kitchens and bathrooms cost more than bedrooms.
- **Rounded-off totals.** ₹10,00,000 looks suspicious. ₹9,87,450 looks calculated.
- **Discount-first.** Drop the rate before the client even asks. Now they will ask again.

## Revising a quotation without losing margin

When the client asks for a 10% discount:

1. Do not flatten across all rooms. Surgical cuts protect specific margins.
2. Drop scope, not rate. "We can hit your number by removing the false ceiling in the dining."
3. Switch a brand. "Greenlam → Merino in the kids room saves ₹14,000."
4. Adjust milestones, not the rate. Offer faster delivery; rate holds.

