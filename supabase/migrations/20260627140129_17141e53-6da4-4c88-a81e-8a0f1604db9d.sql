## Common mistakes

- **Calling an estimate a quotation.** Clients hold you to it.
- **Sending an "invoice" before scope is signed.** Looks aggressive, kills trust.
- **No GSTIN on a tax invoice over the threshold.** Client refuses payment.
- **Proforma showing CGST/SGST.** Auditors flag this — proformas are not tax documents.

