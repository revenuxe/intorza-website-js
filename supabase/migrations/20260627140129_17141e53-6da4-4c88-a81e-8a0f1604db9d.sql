  $body$# Quotation vs Estimate vs Invoice: What Interior Designers Need to Know

These three documents look similar, get confused constantly, and the confusion costs interior studios real money. Here is the clean distinction every designer should internalise.

## The 30-second answer

- **Estimate** — an approximate cost. Non-binding. Used early in conversation.
- **Quotation** — a fixed price offer with line items and validity. Binding once accepted.
- **Invoice** — a bill for work done or to be done. Demands payment.

Misuse any of them and you either lose money or fight a client.

## When to send an estimate

Use an estimate when:

- The brief is still vague.
- You need to give a ballpark before a site visit.
- The client wants "an idea" before committing to a measurement appointment.

Mark it clearly as **ESTIMATE — INDICATIVE ONLY**. Include a range, not a single number. "₹12–18 lakh for a 3BHK turnkey, subject to scope and material selection."

Estimates protect you. Quotations expose you.

## When to send a quotation

Send a quotation only after:

- Site measurement is complete.
- Scope is locked (rooms, items, finishes).
- Brand-wise material choices are made or assumed.

A quotation is a commitment. The price stands for the validity period (typically 15–30 days). Once the client signs or pays advance, you are contractually bound.

A professional quotation includes [everything we covered in the quotation guide](/blog/how-to-make-interior-design-quotation): BOQ, tax, milestones, terms, signatures.

## When to send an invoice

Issue an invoice when:

- Advance is due (proforma or tax invoice).
- A milestone is hit.
- Goods are delivered.
- Project handover is complete.

In India, a **tax invoice** must contain GSTIN, HSN/SAC, CGST/SGST/IGST split, place of supply, and a sequential invoice number. Without those, your client cannot claim input credit and you cannot defend the document in audit.

See our [GST invoice guide](/blog/gst-invoice-interior-designers-india-guide) for the exact format.

## Proforma invoice vs tax invoice

A proforma invoice is a *draft* invoice. It looks like an invoice but is not legally a tax invoice — it is a price commitment to facilitate advance payment.

Use proforma for:

- Advance collection before goods are dispatched.
- Letter-of-credit and import paperwork.

Issue the actual tax invoice on dispatch / service completion. The proforma does not go into your GST returns; the tax invoice does.

## The flow in a real project

```
Estimate  →  Quotation  →  Advance (Proforma)  →  Tax Invoice (per milestone)  →  Final Invoice
```

